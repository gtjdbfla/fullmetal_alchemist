"""Shared navigation for the dashboard and pre-rendered comic reader."""
from pathlib import Path
import json
import re
from html import escape
ROOT = Path(__file__).resolve().parents[1]

def items():
    return json.loads((ROOT / 'site/data/navigation.json').read_text(encoding='utf-8'))

def render_navigation(active):
    links = []
    for item in items():
        current = item['view'] == active
        attributes = ' class="nav-item' + (' active' if current else '') + '"'
        if current: attributes += ' aria-current="page"'
        links.append('<a href="' + escape(item['href'], quote=True) + '"' + attributes + '><span>' + item['number'] + '</span>' + escape(item['label']) + '</a>')
    return ''.join(links)

def build_navigation():
    core = ROOT / 'site/core.mjs'
    source = core.read_text(encoding='utf-8')
    source = source.split('// BEGIN SHARED NAVIGATION')[0].rstrip() + '\n\n'
    source += '// BEGIN SHARED NAVIGATION — generated by scripts/navigation.py\n'
    source += 'export const NAVIGATION = ' + json.dumps(items(),ensure_ascii=False) + ';\n'
    source += """export function renderNavigation(active) {
  return NAVIGATION.map(item => `<a href="${item.href}" class="nav-item${item.view === active ? ' active' : ''}"${item.view === active ? ' aria-current="page"' : ''}${item.view === 'comic' ? '' : ` data-view="${item.view}"`}><span>${item.number}</span>${item.label}</a>`).join('');
}
"""
    core.write_text(source,encoding='utf-8')
    index = ROOT / 'site/index.html'
    template = index.read_text(encoding='utf-8')
    template = re.sub(r'(<nav id="navigation"[^>]*>).*?(</nav>)', lambda match: match[1] + render_navigation('read') + match[2], template, flags=re.S)
    index.write_text(template,encoding='utf-8')
